// ポケモンIDからタイプを取得する関数
export function getPokemonTypes(pokemonId: string): PokemonType[] {
  const typeIds = POKEMON_TYPE_MAPPING[pokemonId] || [];
  return typeIds.map(id => POKEMON_TYPES.find(type => type.id === id)!).filter(Boolean);
}

// タイプIDからタイプ名を取得する関数
export function getTypeName(typeId: number): string {
  const type = POKEMON_TYPES.find(t => t.id === typeId);
  return type ? type.name : '';
}

// タイプ名からタイプ情報を取得する関数
export function getTypeByName(typeName: string): PokemonType | undefined {
  return POKEMON_TYPES.find(type => type.name === typeName);
}